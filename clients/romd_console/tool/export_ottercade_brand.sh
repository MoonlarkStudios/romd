#!/usr/bin/env bash
set -euo pipefail

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
client_dir="$(cd "$script_dir/.." && pwd)"
repo_dir="$(cd "$client_dir/../.." && pwd)"
kit_dir="$repo_dir/brand/ottercade"
icons_dir="$kit_dir/assets/icons"
logos_dir="$kit_dir/assets/logos"
temporary_dir="$(mktemp -d "${TMPDIR:-/tmp}/ottercade-brand.XXXXXX")"
trap 'rm -rf "$temporary_dir"' EXIT

magick_bin="${MAGICK_BIN:-$(command -v magick || true)}"
if [[ -z "$magick_bin" ]]; then
  echo "Native icon placement requires ImageMagick (magick)." >&2
  exit 1
fi

# Placement only: artwork and fonts are approved, checked-in kit inputs.
assets_dir="$client_dir/assets/brand"
mkdir -p "$assets_dir" "$client_dir/assets/fonts"
cp "$logos_dir/mascot-soft/logo.png" "$assets_dir/ottercade_romp.png"
cp "$logos_dir/wordmark-primary/logo.png" "$assets_dir/ottercade_wordmark_ink.png"
cp "$logos_dir/wordmark-reversed/logo.png" "$assets_dir/ottercade_wordmark_cream.png"
cp "$repo_dir/brand/romd/fonts/archivo/"* "$client_dir/assets/fonts/"
cp "$repo_dir/brand/romd/fonts/ibm-plex-mono/"* "$client_dir/assets/fonts/"

resize_png() {
  local source_path="$1" output_path="$2" size="$3"
  mkdir -p "$(dirname "$output_path")"
  "$magick_bin" "$source_path" -filter Lanczos -resize "${size}x${size}" -strip \
    -define png:exclude-chunk=date,time "$output_path"
}

# macOS owns the corner mask: use the approved opaque square, not a plated icon.
mac_icon_dir="$client_dir/macos/Runner/Assets.xcassets/AppIcon.appiconset"
for size in 16 32 64 128 256 512; do
  resize_png "$icons_dir/square/icon.png" "$mac_icon_dir/app_icon_${size}.png" "$size"
done
cp "$icons_dir/square/icon.png" "$mac_icon_dir/app_icon_1024.png"

# Keep the existing Android 108 dp canvas and 66 dp foreground safe area.
android_res="$client_dir/android/app/src/main/res"
android_xxxhdpi="$android_res/drawable-xxxhdpi"
resize_png "$logos_dir/mascot-soft/logo.png" "$android_xxxhdpi/ottercade_launch_mark.png" 880
"$magick_bin" "$logos_dir/mascot-soft/logo.png" -filter Lanczos -resize 264x264 \
  -gravity center -background none -extent 432x432 -strip \
  -define png:exclude-chunk=date,time "$android_xxxhdpi/ottercade_launcher_foreground.png"

# This fixed icon plate is independent of the application-owned splash/theme.
python3 - "$kit_dir/tokens.json" "$android_res/values/ottercade_brand.xml" <<'PY'
import json
import sys
from pathlib import Path

token = json.loads(Path(sys.argv[1]).read_text())["palette"]["tile"]["$value"]
assert token["colorSpace"] == "srgb" and len(token["components"]) == 3
color = "#" + "".join(f"{round(channel * 255):02X}" for channel in token["components"])
Path(sys.argv[2]).write_text(
    '<?xml version="1.0" encoding="utf-8"?>\n'
    '<!-- Generated by tool/export_ottercade_brand.sh from the copied kit. -->\n'
    '<resources>\n'
    f'    <color name="ottercade_icon_background">{color}</color>\n'
    '</resources>\n'
)
PY

# These are generated resolutions of one approved drawing, not optical variants.
declare -a android_densities=(mdpi hdpi xhdpi xxhdpi xxxhdpi)
declare -a android_sizes=(48 72 96 144 192)
for index in "${!android_densities[@]}"; do
  size="${android_sizes[$index]}"
  resize_png "$icons_dir/standard/icon.png" \
    "$android_res/mipmap-${android_densities[$index]}/ic_launcher.png" "$size"
done

# Assemble Windows' required frames from the same canonical source.
windows_pngs=()
for size in 16 24 32 48 64 128 256; do
  output_path="$temporary_dir/windows_${size}.png"
  resize_png "$icons_dir/standard/icon.png" "$output_path" "$size"
  windows_pngs+=("$output_path")
done
"$magick_bin" "${windows_pngs[@]}" "$client_dir/windows/runner/resources/app_icon.ico"
resize_png "$icons_dir/standard/icon.png" "$client_dir/linux/runner/resources/ottercade.png" 512

echo "Ottercade assets placed from brand/ottercade; source: brand/ottercade/SOURCE.md."
echo "Console body fonts placed from brand/romd; source: brand/romd/SOURCE.md."
