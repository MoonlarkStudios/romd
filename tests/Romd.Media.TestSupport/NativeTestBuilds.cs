using System.Diagnostics;
using System.Runtime.InteropServices;
using System.Security.Cryptography;
using System.Text.Json;
using System.Text.Json.Nodes;

namespace Romd.Media.TestSupport;

/// <summary>Native builds for tests: the repository's own <c>artifacts/</c> outputs, or synthetic build records.</summary>
/// <remarks>A missing artifact fails the test and names the task that builds it; nothing is skipped or searched for.</remarks>
public static class NativeTestBuilds
{
    public const string BuildTask = "mise run native:test-inputs";

    public static string RepositoryRoot { get; } = FindRepositoryRoot();

    /// <summary>The portable RID the artifacts of this process are built for.</summary>
    public static string Rid { get; } = (OperatingSystem.IsLinux()
        ? RuntimeInformation.RuntimeIdentifier.Contains("musl", StringComparison.Ordinal) ? "linux-musl" : "linux"
        : OperatingSystem.IsMacOS() ? "osx" : "win") + "-" + RuntimeInformation.ProcessArchitecture.ToString().ToLowerInvariant();

    /// <summary>The libchdr build directory <c>artifacts/native/libchdr/&lt;rid&gt;</c>.</summary>
    public static string LibchdrDirectory => RequireBuild(Path.Combine(RepositoryRoot, "artifacts", "native", "libchdr", Rid));

    /// <summary>The chdman build directory <c>artifacts/tools/chdman/&lt;rid&gt;</c>.</summary>
    public static string ChdmanDirectory => RequireBuild(Path.Combine(RepositoryRoot, "artifacts", "tools", "chdman", Rid));

    /// <summary>A synthetic libchdr fixture generated by the pinned chdman.</summary>
    public static string LibchdrFixture(string name)
    {
        string path = Path.Combine(RepositoryRoot, "artifacts", "fixtures", "libchdr-final", name);
        return File.Exists(path) ? path
            : throw new InvalidOperationException($"Native test fixture '{path}' is missing; run `{BuildTask}`.");
    }

    /// <summary>Copies a build directory's record and binary, so a test may change the copy.</summary>
    public static string CopyBuild(string source, string destination)
    {
        Directory.CreateDirectory(Path.Combine(destination, "native"));
        File.Copy(Path.Combine(source, "build-manifest.json"), Path.Combine(destination, "build-manifest.json"));
        foreach (string file in Directory.EnumerateFiles(Path.Combine(source, "native")))
            File.Copy(file, Path.Combine(destination, "native", Path.GetFileName(file)));
        return destination;
    }

    /// <summary>Rewrites one build record through <paramref name="change"/>.</summary>
    public static void ChangeRecord(string buildDirectory, Action<JsonNode> change)
    {
        string path = Path.Combine(buildDirectory, "build-manifest.json");
        JsonNode record = JsonNode.Parse(File.ReadAllBytes(path)) ?? throw new InvalidDataException("Empty build record.");
        change(record);
        File.WriteAllBytes(path, JsonSerializer.SerializeToUtf8Bytes(record));
    }

    /// <summary>Writes a libchdr directory with a synthetic binary and the schema 3 record describing it.</summary>
    public static string WriteLibchdrBuild(string directory, byte[] binary, string rid, string upstreamCommit,
        int recipeVersion = 1, string file = "libmoonlark_chdr.so", string buildId = "", string upstreamVersion = "v0.3.0-test",
        string familyVersion = "1.0.0-preview.1")
    {
        Directory.CreateDirectory(Path.Combine(directory, "native"));
        File.WriteAllBytes(Path.Combine(directory, "native", Path.GetFileName(file)), binary);
        string build = buildId.Length == 0 ? new string('e', 64) : buildId;
        var record = new JsonObject
        {
            ["schemaVersion"] = 3,
            ["product"] = "moonlark_chdr",
            ["rid"] = rid,
            ["file"] = file,
            ["size"] = binary.LongLength,
            ["sha256"] = Sha256(binary),
            ["upstreamCommit"] = upstreamCommit,
            ["upstreamVersion"] = upstreamVersion,
            ["recipeVersion"] = recipeVersion,
            ["nativeVersion"] = familyVersion,
            ["managedVersion"] = familyVersion,
            ["qualification"] = "synthetic-test-record",
            ["attestation"] = null,
            ["buildInfo"] = new JsonObject
            {
                ["buildId"] = build,
                ["upstreamCommit"] = upstreamCommit,
                ["upstreamVersion"] = upstreamVersion,
                ["nativeVersion"] = familyVersion,
                ["managedVersion"] = familyVersion,
                ["features"] = new JsonArray("raw-sectors", "subcode", "block-crc")
            }
        };
        File.WriteAllBytes(Path.Combine(directory, "build-manifest.json"), JsonSerializer.SerializeToUtf8Bytes(record));
        return directory;
    }

    /// <summary>Writes a chdman directory with a synthetic binary and the schema 2 record describing it.</summary>
    public static string WriteChdmanBuild(string directory, byte[] binary, string rid, string mameTag, string mameSourceSha256,
        int recipeVersion = 1)
    {
        Directory.CreateDirectory(Path.Combine(directory, "native"));
        File.WriteAllBytes(Path.Combine(directory, "native", "chdman"), binary);
        WriteChdmanRecord(directory, binary, rid, mameTag, mameSourceSha256, recipeVersion);
        return directory;
    }

    /// <summary>Compiles the synthetic foreign-process tool (it is not chdman) into a recorded build directory.</summary>
    /// <remarks>Linux only, with the existing Clang; a missing compiler fails rather than skips.</remarks>
    public static string CompileChdDvdToolFixture(string directory, string mameTag, string mameSourceSha256)
    {
        if (!OperatingSystem.IsLinux())
            throw new PlatformNotSupportedException("The synthetic DVD tool fixture is a Linux payload.");
        string source = Path.Combine(RepositoryRoot, "tests", "Romd.Media.Tests", "PlayStation", "ChdDvdToolFixture.c");
        string binary = Path.Combine(directory, "native", "chdman");
        Directory.CreateDirectory(Path.GetDirectoryName(binary)!);
        var start = new ProcessStartInfo("clang") { UseShellExecute = false, RedirectStandardError = true, RedirectStandardOutput = true };
        foreach (string argument in new[] { "-std=c17", "-O2", "-g0", "-Wall", "-Wextra", "-Werror", "-x", "c", source, "-o", binary })
            start.ArgumentList.Add(argument);
        Process compiler;
        try
        { compiler = Process.Start(start) ?? throw new InvalidOperationException("Clang did not start."); }
        catch (System.ComponentModel.Win32Exception error)
        { throw new InvalidOperationException("The synthetic DVD tool fixture requires the existing Clang; no fallback.", error); }
        using (compiler)
        {
            string diagnostics = compiler.StandardError.ReadToEnd() + compiler.StandardOutput.ReadToEnd();
            compiler.WaitForExit();
            if (compiler.ExitCode != 0)
                throw new InvalidOperationException("Synthetic DVD tool fixture compile failed: " + diagnostics);
        }
        File.SetUnixFileMode(binary, UnixFileMode.UserRead | UnixFileMode.UserExecute | UnixFileMode.GroupRead |
            UnixFileMode.GroupExecute | UnixFileMode.OtherRead | UnixFileMode.OtherExecute);
        WriteChdmanRecord(directory, File.ReadAllBytes(binary), Rid, mameTag, mameSourceSha256, 1);
        return directory;
    }

    private static void WriteChdmanRecord(string directory, byte[] binary, string rid, string mameTag, string mameSourceSha256,
        int recipeVersion)
    {
        var record = new JsonObject
        {
            ["schemaVersion"] = 2,
            ["recipeVersion"] = recipeVersion,
            ["qualification"] = "synthetic-test-record",
            ["attestation"] = null,
            ["rid"] = rid,
            ["pin"] = new JsonObject { ["tag"] = mameTag, ["sourceSha256"] = mameSourceSha256 },
            ["binary"] = new JsonObject { ["path"] = "native/chdman", ["sha256"] = Sha256(binary), ["bytes"] = binary.LongLength }
        };
        File.WriteAllBytes(Path.Combine(directory, "build-manifest.json"), JsonSerializer.SerializeToUtf8Bytes(record));
    }

    private static string RequireBuild(string directory) => File.Exists(Path.Combine(directory, "build-manifest.json"))
        ? directory
        : throw new InvalidOperationException($"Native build '{directory}' is missing its build-manifest.json; run `{BuildTask}`.");

    private static string Sha256(byte[] bytes) => Convert.ToHexStringLower(SHA256.HashData(bytes));

    private static string FindRepositoryRoot()
    {
        for (var directory = new DirectoryInfo(AppContext.BaseDirectory); directory is not null; directory = directory.Parent)
            if (File.Exists(Path.Combine(directory.FullName, "Romd.sln")))
                return directory.FullName;
        throw new InvalidOperationException("Native test builds require the ROMD repository root.");
    }
}
