using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Storage;
using Npgsql;
using Romd.Admin.Application.Common.Persistence;
using Romd.Infrastructure.Tests.Helpers;
using Romd.Persistence;
using Romd.Persistence.MediaFacts;
using Shouldly;
using Xunit;

namespace Romd.Infrastructure.Tests.Persistence;

public sealed partial class CatalogCdLayoutBoundaryTests
{
    [Theory]
    [InlineData("before-rollback")]
    [InlineData("after-rollback")]
    [InlineData("release")]
    public async Task Binding_CancelledAfterActualInsertAndRecoveryFails_PreservesOriginalAndOuterRollback(string failure)
    {
        using var cancellation = new CancellationTokenSource();
        var cancel = new CancelAfterMediaInsert("INSERT INTO romd.\"CatalogCdLayoutBindings\"",
            "SELECT count(*) FROM romd.\"CatalogCdLayoutBindings\"", cancellation);
        await using var db = new RomdDbContext(database.CreateOptions(options => options
            .ReplaceService<IRelationalTransactionFactory, CatalogTransactionFaults.Factory>().AddInterceptors(cancel)));
        var faults = BindingSavepointFaults(failure);
        faults.Register(db);
        await using (var transaction = await db.Database.BeginTransactionAsync())
        {
            var graph = await GraphAsync(db, Decoder, preferred: true, ObservedContainer(canonical: false));

            var observed = await Record.ExceptionAsync(() => new CatalogCdLayoutStore(db)
                .PublishAsync(Publication(graph.Id, Guid.NewGuid()), cancellation.Token));

            observed.ShouldBeSameAs(cancel.Primary);
            cancel.Primary.CancellationToken.ShouldBe(cancellation.Token);
            cancel.Primary.Data["Romd.CatalogCdLayout.SavepointRecoveryFailure"].ShouldBeSameAs(
                failure == "release" ? faults.SavepointReleaseFailure : faults.SavepointFailure);
            await transaction.RollbackAsync(CancellationToken.None);
        }

        cancel.Reached.ShouldBeTrue();
        cancel.InsertedRows.ShouldBe(1);
        faults.CommitAttempts.ShouldBe(0);
        faults.RollbackAttempts.ShouldBe(1);
        faults.SavepointRollbackAttempts.ShouldBe(1);
        faults.Disposals.ShouldBe(1);
        await AssertAbortedBindingAsync();
    }

    [Theory]
    [InlineData("before-rollback")]
    [InlineData("after-rollback")]
    [InlineData("release")]
    public async Task Binding_SourceChangedAndRecoveryFails_DoesNotReturnBusinessConflictOrContinuePublication(string failure)
    {
        await using var db = new RomdDbContext(database.CreateOptions(options =>
            options.ReplaceService<IRelationalTransactionFactory, CatalogTransactionFaults.Factory>()));
        var faults = BindingSavepointFaults(failure);
        faults.Register(db);
        await using (var transaction = await db.Database.BeginTransactionAsync())
        {
            var graph = await GraphAsync(db, Decoder, preferred: true, ObservedContainer(canonical: false));
            (await db.CatalogReleaseFiles.Where(row => row.Id == 2).ExecuteUpdateAsync(update => update
                .SetProperty(row => row.Size, Cue.Size).SetProperty(row => row.Sha1, Cue.Sha1)
                .SetProperty(row => row.Md5, Cue.Md5).SetProperty(row => row.Crc, Cue.Crc32))).ShouldBe(1);
            var publication = Publication(graph.Id, Guid.NewGuid());
            publication = publication with
            {
                Requirement = publication.Requirement with { Size = Cue.Size, Sha1 = Cue.Sha1, Md5 = Cue.Md5, Crc32 = Cue.Crc32 }
            };
            // Exact generated bytes require a verified ordinary original; this graph has none.
            var observed = await Record.ExceptionAsync(() => new CatalogCdLayoutStore(db).PublishAsync(publication, default));

            observed.ShouldBeSameAs(failure == "release" ? faults.SavepointReleaseFailure : faults.SavepointFailure);
            var primary = observed!.Data["Romd.CatalogCdLayout.PublicationFailure"].ShouldBeOfType<PostgresException>();
            primary.SqlState.ShouldBe(PostgresErrorCodes.CheckViolation);
            primary.ConstraintName.ShouldBe("catalog_cd_layout_original_changed");
            new EfUnitOfWork(db).ConflictOf(observed!).ShouldBe(TransactionConflict.None);
            // A failed restoration must escape before SourceChanged or another publication can be accepted.
            await transaction.RollbackAsync(CancellationToken.None);
        }

        faults.CommitAttempts.ShouldBe(0);
        faults.RollbackAttempts.ShouldBe(1);
        faults.SavepointRollbackAttempts.ShouldBe(1);
        await AssertAbortedBindingAsync();
    }

    private static CatalogTransactionFaults BindingSavepointFaults(string failure) => new(
        failBeforeSavepointRollback: failure == "before-rollback", failSavepointRollback: failure == "after-rollback",
        failSavepointRelease: failure == "release", failDisposal: false, savepointName: "catalog_cd_layout_publication");

    private async Task AssertAbortedBindingAsync()
    {
        await using var verify = database.CreateContext();
        (await CountAsync(verify, "CatalogCdLayoutBindings")).ShouldBe(0);
        (await CountAsync(verify, "Roms")).ShouldBe(0);
        (await CountAsync(verify, "Verifications")).ShouldBe(0);
        (await verify.JobItems.CountAsync()).ShouldBe(0);
        (await verify.Files.CountAsync()).ShouldBe(2);
    }
}
