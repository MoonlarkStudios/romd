#!/usr/bin/env python3
"""Verify SDK whitespace formatting of changed maintained C# files, without restore or edits."""
import argparse
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[2]
SOURCE_ROOTS = {'src', 'tests', 'tools', 'benchmarks'}
GENERATED_SUFFIXES = ('.g.cs', '.generated.cs', '.designer.cs', 'modelsnapshot.cs')


def git(root, *arguments):
    return subprocess.check_output(['git', *arguments], cwd=root, stderr=subprocess.PIPE).decode(
        'utf-8', errors='surrogateescape')


def inventory(root):
    return set(git(root, 'ls-files', '--cached', '--others', '--exclude-standard', '-z').split('\0')) - {''}


def maintained(root, relative):
    path = Path(relative)
    if path.parts[0] not in SOURCE_ROOTS or path.suffix != '.cs':
        return False
    if any(part in {'bin', 'obj'} for part in path.parts) or path.name.lower().endswith(GENERATED_SUFFIXES):
        return False
    source = root / path
    if not source.is_file():
        return False
    if not source.resolve().is_relative_to(root.resolve()):
        raise ValueError(f'C# input escapes this checkout: {relative}')
    header = source.read_bytes()[:2048].lower()
    return b'<auto-generated' not in header and b'<autogenerated' not in header


def selected_files(root, base):
    # Git reports no previous tip for a newly created ref. Verify its entire
    # maintained tree, including the first public root commit, without a parent.
    if base in {'0' * 40, '0' * 64}:
        git(root, 'rev-parse', '--verify', '--end-of-options', 'HEAD^{commit}')
        return sorted(name for name in inventory(root) if maintained(root, name))
    # Resolve the ref before passing its value to other Git commands. Missing history fails closed.
    revision = git(root, 'rev-parse', '--verify', '--end-of-options', base + '^{commit}').strip()
    ancestor = git(root, 'merge-base', revision, 'HEAD').strip()
    changed = set(git(root, 'diff', '--name-only', '--no-renames', '-z', ancestor, '--').split('\0')) - {''}
    changed.update(git(root, 'ls-files', '--others', '--exclude-standard', '-z').split('\0'))
    configs = [Path(name) for name in changed if Path(name).name == '.editorconfig']
    candidates = changed - {''}
    if configs:
        # A formatting-policy edit applies to all maintained files beneath that config, including
        # deleted policies whose settings now fall back to the parent. Never hide it behind the diff.
        candidates.update(name for name in inventory(root)
                          if any(Path(name).is_relative_to(config.parent) for config in configs))
    return sorted(name for name in candidates if maintained(root, name))


def formatter_command(root, paths):
    # Absolute include paths preserve spaces and option-like filenames without invoking a shell.
    return ['dotnet', 'format', 'whitespace', str(root), '--folder',
            '--verify-no-changes', '--verbosity', 'minimal', '--include',
            *(str(root / path) for path in paths)]


def verify(root, paths):
    if not paths:
        print('C# whitespace: no changed maintained C# files; formatter not run.')
        return 0
    print(f'C# whitespace: checking {len(paths)} complete file(s), excluding generated code.', flush=True)
    return subprocess.run(formatter_command(root, paths), cwd=root, check=False).returncode


def smoke_test(root):
    """Exercise the installed, pinned SDK with both a rejected and an accepted real C# fixture."""
    expected = json.loads((root / 'global.json').read_text())['sdk']['version']
    actual = subprocess.check_output(['dotnet', '--version'], cwd=root, text=True).strip()
    if actual != expected:
        raise ValueError(f'Expected .NET SDK {expected}, found {actual}; use mise exec or mise run.')
    with tempfile.TemporaryDirectory(prefix='romd-dotnet-style-') as temporary:
        fixture = Path(temporary)
        # Retain strict SDK selection even though the fixture lives outside this checkout.
        (fixture / 'global.json').write_text((root / 'global.json').read_text())
        (fixture / '.editorconfig').write_text('root = true\n[*.cs]\nindent_style = space\n'
                                             'indent_size = 4\ncsharp_new_line_before_open_brace = all\n')
        source = fixture / 'Example.cs'
        source.write_text('class Example{ }\n')
        rejected = subprocess.run(formatter_command(fixture, ['Example.cs']), cwd=fixture,
                                  capture_output=True, text=True, check=False)
        if rejected.returncode != 2 or source.read_text() != 'class Example{ }\n':
            raise ValueError(f'Formatter must reject whitespace without changing files (exit 2):\n'
                             f'{rejected.stdout}{rejected.stderr}')
        source.write_text('class Example\n{\n}\n')
        accepted = subprocess.run(formatter_command(fixture, ['Example.cs']), cwd=fixture,
                                  capture_output=True, text=True, check=False)
        if accepted.returncode != 0 or source.read_text() != 'class Example\n{\n}\n':
            raise ValueError(f'Formatter must accept canonical whitespace without changing files:\n'
                             f'{accepted.stdout}{accepted.stderr}')
    print(f'C# whitespace smoke passed with .NET SDK {actual}: invalid rejected, valid accepted, files unchanged.')
    return 0


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    selection = parser.add_mutually_exclusive_group()
    selection.add_argument('--base', default=os.environ.get('ROMD_DOTNET_STYLE_BASE', 'origin/main'),
                           help='Git base ref; checks changes since its merge base with HEAD, plus local edits. '
                                'An all-zero Git object ID means a new ref and checks all maintained C# files.')
    selection.add_argument('--smoke-test', action='store_true', help='Exercise the pinned SDK formatter on disposable fixtures.')
    args = parser.parse_args()
    try:
        return smoke_test(ROOT) if args.smoke_test else verify(ROOT, selected_files(ROOT, args.base))
    except (OSError, subprocess.CalledProcessError, ValueError) as error:
        print(f'C# whitespace check failed: {error}', file=sys.stderr)
        if isinstance(error, subprocess.CalledProcessError) and error.stderr:
            print(error.stderr.decode('utf-8', errors='replace').strip(), file=sys.stderr)
        print('Restore Git base history and the pinned SDK; no formatting failures are ignored.', file=sys.stderr)
        return 1


if __name__ == '__main__':
    sys.exit(main())
