"""Behavioral coverage for incremental C# selection and fail-closed formatter execution."""
from contextlib import redirect_stdout
import io
from pathlib import Path
import subprocess
import tempfile
import unittest
from unittest.mock import patch

import dotnet_style


class StyleSelectionTests(unittest.TestCase):
    def setUp(self):
        temporary = tempfile.TemporaryDirectory(prefix='romd-style-test-')
        self.addCleanup(temporary.cleanup)
        self.root = Path(temporary.name)
        self.git('init', '--quiet', '--initial-branch=topic')
        self.write('src/Original.cs')
        self.write('src/Deleted.cs')
        self.write('src/Other.cs')
        self.commit()
        self.base = self.git('rev-parse', 'HEAD').strip()

    def git(self, *arguments):
        return dotnet_style.git(self.root, *arguments)

    def write(self, name, content='class Example { }\n'):
        path = self.root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
        return path

    def commit(self):
        self.git('add', '.')
        self.git('-c', 'user.name=Style Test', '-c', 'user.email=style@example.invalid',
                 '-c', 'commit.gpgsign=false', 'commit', '--quiet', '-m', 'Fixture')

    def test_includes_branch_staged_unstaged_and_untracked_changes_only(self):
        self.write('src/Committed.cs')
        self.commit()
        self.write('src/Staged.cs')
        self.git('add', 'src/Staged.cs')
        self.write('src/Original.cs', 'class Changed { }\n')
        self.write('tests/Space and\nnewline.cs')
        self.write('docs/Example.cs')
        self.write('src/Readme.md', '# Example\n')
        self.assertEqual(['src/Committed.cs', 'src/Original.cs', 'src/Staged.cs',
                          'tests/Space and\nnewline.cs'], dotnet_style.selected_files(self.root, self.base))

    def test_uses_merge_base_and_does_not_revert_unrelated_upstream_changes(self):
        self.git('branch', 'upstream')
        self.write('src/Topic.cs')
        self.commit()
        self.git('switch', '--quiet', 'upstream')
        self.write('src/Upstream.cs')
        self.commit()
        self.git('switch', '--quiet', 'topic')
        self.assertEqual(['src/Topic.cs'], dotnet_style.selected_files(self.root, 'upstream'))

    def test_renamed_destination_is_checked_and_deleted_sources_are_omitted(self):
        self.git('mv', 'src/Original.cs', 'src/Renamed.cs')
        (self.root / 'src/Deleted.cs').unlink()
        self.assertEqual(['src/Renamed.cs'], dotnet_style.selected_files(self.root, self.base))

    def test_generated_and_build_outputs_are_excluded(self):
        for name in ['Generated.g.cs', 'Generated.generated.cs', 'Migration.Designer.cs', 'DbModelSnapshot.cs',
                     'bin/Example.cs', 'obj/Example.cs']:
            self.write('src/' + name)
        self.write('src/GeneratorOutput.cs', '// <auto-generated/>\nclass Generated {}\n')
        self.write('src/OtherGenerator.cs', '// <autogenerated>\nclass Generated {}\n')
        self.write('.gitignore', 'src/Ignored.cs\n')
        self.write('src/Ignored.cs')
        self.write('tools/Handwritten.cs')
        self.assertEqual(['tools/Handwritten.cs'], dotnet_style.selected_files(self.root, self.base))

    def test_root_editorconfig_change_checks_all_maintained_files(self):
        self.write('.editorconfig', 'root = true\n')
        self.assertEqual(['src/Deleted.cs', 'src/Original.cs', 'src/Other.cs'],
                         dotnet_style.selected_files(self.root, self.base))

    def test_nested_editorconfig_change_only_broadens_its_own_subtree(self):
        self.write('tests/Original.cs')
        self.commit()
        self.base = self.git('rev-parse', 'HEAD').strip()
        self.write('tests/.editorconfig', 'root = false\n')
        self.assertEqual(['tests/Original.cs'], dotnet_style.selected_files(self.root, self.base))

    def test_deleted_or_moved_editorconfig_checks_the_old_scope_too(self):
        self.write('src/.editorconfig', 'root = false\n')
        self.commit()
        base = self.git('rev-parse', 'HEAD').strip()
        self.git('mv', 'src/.editorconfig', 'tests.editorconfig')
        self.assertEqual(['src/Deleted.cs', 'src/Original.cs', 'src/Other.cs'],
                         dotnet_style.selected_files(self.root, base))

    def test_missing_base_is_an_error_instead_of_an_empty_pass(self):
        with self.assertRaises(subprocess.CalledProcessError), redirect_stdout(io.StringIO()):
            dotnet_style.selected_files(self.root, 'missing-ref')

    def test_new_ref_checks_the_complete_root_commit_and_local_changes(self):
        self.write('src/Generated.g.cs')
        self.write('docs/Example.cs')
        self.write('src/Original.cs', 'class Changed {}\n')
        self.write('tests/Staged.cs')
        self.git('add', 'tests/Staged.cs')
        self.write('tools/Untracked.cs')
        self.assertEqual('1', self.git('rev-list', '--count', 'HEAD').strip())
        for base in ('0' * 40, '0' * 64):
            with self.subTest(base=base):
                self.assertEqual(['src/Deleted.cs', 'src/Original.cs', 'src/Other.cs',
                                  'tests/Staged.cs', 'tools/Untracked.cs'],
                                 dotnet_style.selected_files(self.root, base))

    def test_new_ref_checks_unchanged_files_even_with_multiple_commits(self):
        self.write('src/Later.cs')
        self.commit()
        (self.root / 'src/Deleted.cs').unlink()
        self.assertEqual(['src/Later.cs', 'src/Original.cs', 'src/Other.cs'],
                         dotnet_style.selected_files(self.root, '0' * 40))

    def test_new_ref_requires_a_commit_and_does_not_accept_a_short_zero_ref(self):
        with self.assertRaises(subprocess.CalledProcessError):
            dotnet_style.selected_files(self.root, '0000')
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            dotnet_style.git(root, 'init', '--quiet')
            with self.assertRaises(subprocess.CalledProcessError):
                dotnet_style.selected_files(root, '0' * 40)

    def test_source_symlink_outside_checkout_is_rejected(self):
        with tempfile.TemporaryDirectory() as outside:
            source = Path(outside) / 'Outside.cs'
            source.write_text('class Outside {}\n')
            (self.root / 'src/Alias.cs').symlink_to(source)
            with self.assertRaisesRegex(ValueError, 'escapes this checkout'):
                dotnet_style.selected_files(self.root, self.base)


class FormatterExecutionTests(unittest.TestCase):
    def test_empty_selection_does_not_invoke_formatter(self):
        with patch('dotnet_style.subprocess.run') as run, redirect_stdout(io.StringIO()):
            self.assertEqual(0, dotnet_style.verify(Path('/repo'), []))
        run.assert_not_called()

    def test_formatter_failure_is_preserved_and_arguments_cannot_become_shell_commands(self):
        root = Path('/repo')
        name = 'src/Name with $(literal) spaces.cs'
        with patch('dotnet_style.subprocess.run') as run, redirect_stdout(io.StringIO()):
            run.return_value.returncode = 2
            self.assertEqual(2, dotnet_style.verify(root, [name]))
        command = run.call_args.args[0]
        self.assertEqual(['dotnet', 'format', 'whitespace', '/repo'], command[:4])
        self.assertIn('--folder', command)
        self.assertIn('--verify-no-changes', command)
        self.assertNotIn('--no-restore', command)  # The SDK rejects this with --folder.
        self.assertEqual('/repo/' + name, command[-1])
        self.assertNotIn('shell', run.call_args.kwargs)


if __name__ == '__main__':
    unittest.main()
